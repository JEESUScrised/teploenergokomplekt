export function projectsForTags(tags?: string[]): Project[] {
  if (!tags?.length) return projects.slice(0, 4);
  const matched = projects.filter((p) =>
    tags.some((tag) => p.id.includes(tag) || p.src.includes(tag)),
  );
  return matched.length >= 3 ? matched.slice(0, 6) : projects.slice(0, 4);
}
